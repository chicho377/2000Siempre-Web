  const storageKey = "siteLanguage";
  const html = document.documentElement;

  const interpolate = (text, vars = {}) =>
    Object.entries(vars).reduce(
      (result, [key, value]) => result.replaceAll(`{${key}}`, value),
      text
    );

  const t = (key, vars) => {
    const lang = html.getAttribute("lang") || "es";
    const value = translations[lang]?.[key] ?? translations.es[key];
    if (typeof value !== "string") {
      return key;
    }
    return vars ? interpolate(value, vars) : value;
  };

  const applyTranslations = (lang) => {
    html.setAttribute("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;
      if (!key) return;
      element.textContent = t(key);
    });

    document.querySelectorAll("[data-i18n-html]").forEach((element) => {
      const key = element.dataset.i18nHtml;
      if (!key) return;
      element.innerHTML = t(key);
    });

    document.querySelectorAll("[data-i18n-attrs]").forEach((element) => {
      const raw = element.dataset.i18nAttrs;
      if (!raw) return;
      raw.split(",").forEach((pair) => {
        const [attr, key] = pair.split(":").map((item) => item.trim());
        if (!attr || !key) return;
        element.setAttribute(attr, t(key));
      });
    });
  };

  const setLanguage = (lang) => {
    const next = translations[lang] ? lang : "es";
    localStorage.setItem(storageKey, next);
    applyTranslations(next);
  };

  const toggleLanguage = () => {
    const current = html.getAttribute("lang") || "es";
    setLanguage(current === "es" ? "en" : "es");
  };

  window.siteI18n = {
    t,
    setLanguage,
    toggleLanguage,
    getLanguage: () => html.getAttribute("lang") || "es",
  };

  const stored = localStorage.getItem(storageKey);
  const initial = translations[stored] ? stored : "es";
  applyTranslations(initial);

  const toggleButton = document.getElementById("languageToggle");
  toggleButton?.addEventListener("click", toggleLanguage);
